package main

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

const maxStock = 10000

// Set at build time via -ldflags "-X main.version=...".
var (
	version   = "dev"
	commit    = "unknown"
	buildTime = "unknown"
)

const schema = `
CREATE TABLE IF NOT EXISTS items (
	id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name  text    NOT NULL,
	stock integer NOT NULL CHECK (stock BETWEEN 0 AND 10000)
);
INSERT INTO items (id, name, stock) VALUES
	(1, 'bolt', 120), (2, 'nut', 340), (3, 'washer', 8), (4, 'hinge', 3), (5, 'bracket', 57)
ON CONFLICT (id) DO NOTHING;
SELECT setval(pg_get_serial_sequence('items', 'id'), (SELECT max(id) FROM items));
`

type item struct {
	ID    int    `json:"id"`
	Name  string `json:"name"`
	Stock int    `json:"stock"`
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: depot serve|migrate|version")
		os.Exit(2)
	}
	logger := slog.New(slog.NewJSONHandler(os.Stdout, nil))

	var err error
	switch os.Args[1] {
	case "serve":
		err = serve(logger)
	case "migrate":
		err = migrate(logger)
	case "version":
		err = json.NewEncoder(os.Stdout).Encode(versionInfo())
	default:
		err = fmt.Errorf("unknown command %q", os.Args[1])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func versionInfo() map[string]string {
	return map[string]string{"version": version, "commit": commit, "build_time": buildTime}
}

func validateItem(name string, stock int) error {
	if strings.TrimSpace(name) == "" {
		return errors.New("name must not be empty")
	}
	if stock < 0 || stock > maxStock {
		return fmt.Errorf("stock must be between 0 and %d", maxStock)
	}
	return nil
}

// The process does not retry: waiting for the database belongs to the environment.
func connect() (*pgxpool.Pool, error) {
	url := os.Getenv("DATABASE_URL")
	if url == "" {
		return nil, errors.New("DATABASE_URL is not set")
	}
	pool, err := pgxpool.New(context.Background(), url)
	if err != nil {
		return nil, err
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("database not reachable: %w", err)
	}
	return pool, nil
}

func migrate(logger *slog.Logger) error {
	pool, err := connect()
	if err != nil {
		return err
	}
	defer pool.Close()

	ctx := context.Background()
	if _, err := pool.Exec(ctx, schema); err != nil {
		return fmt.Errorf("migration failed: %w", err)
	}
	var count int
	if err := pool.QueryRow(ctx, "SELECT count(*) FROM items").Scan(&count); err != nil {
		return err
	}
	logger.Info("schema ready", "items", count)
	return nil
}

func serve(logger *slog.Logger) error {
	token := os.Getenv("API_TOKEN")
	if token == "" {
		return errors.New("API_TOKEN is not set")
	}
	port := os.Getenv("PORT")
	if port == "" {
		port = "8000"
	}
	pool, err := connect()
	if err != nil {
		return err
	}
	defer pool.Close()

	dbError := func(w http.ResponseWriter, err error) {
		logger.Error("database", "error", err.Error())
		writeError(w, http.StatusInternalServerError, "database error")
	}

	mux := http.NewServeMux()
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
	})
	mux.HandleFunc("GET /version", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, http.StatusOK, versionInfo())
	})
	mux.HandleFunc("GET /readyz", func(w http.ResponseWriter, r *http.Request) {
		ctx, cancel := context.WithTimeout(r.Context(), time.Second)
		defer cancel()
		if err := pool.Ping(ctx); err != nil {
			writeJSON(w, http.StatusServiceUnavailable, map[string]string{"status": "database unreachable"})
			return
		}
		writeJSON(w, http.StatusOK, map[string]string{"status": "ready"})
	})
	mux.HandleFunc("GET /api/items", func(w http.ResponseWriter, r *http.Request) {
		rows, _ := pool.Query(r.Context(), "SELECT id, name, stock FROM items ORDER BY id")
		items, err := pgx.CollectRows(rows, pgx.RowToStructByPos[item])
		if err != nil {
			dbError(w, err)
			return
		}
		writeJSON(w, http.StatusOK, items)
	})
	mux.HandleFunc("GET /api/items/{id}", func(w http.ResponseWriter, r *http.Request) {
		id, err := strconv.Atoi(r.PathValue("id"))
		if err != nil {
			writeError(w, http.StatusBadRequest, "id must be a number")
			return
		}
		var it item
		err = pool.QueryRow(r.Context(), "SELECT id, name, stock FROM items WHERE id = $1", id).
			Scan(&it.ID, &it.Name, &it.Stock)
		if errors.Is(err, pgx.ErrNoRows) {
			writeError(w, http.StatusNotFound, "item not found")
			return
		}
		if err != nil {
			dbError(w, err)
			return
		}
		writeJSON(w, http.StatusOK, it)
	})
	mux.HandleFunc("POST /api/items", func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Bearer "+token {
			writeError(w, http.StatusUnauthorized, "missing or wrong bearer token")
			return
		}
		var in struct {
			Name  string `json:"name"`
			Stock int    `json:"stock"`
		}
		if err := json.NewDecoder(r.Body).Decode(&in); err != nil {
			writeError(w, http.StatusBadRequest, "body must be JSON")
			return
		}
		if err := validateItem(in.Name, in.Stock); err != nil {
			writeError(w, http.StatusBadRequest, err.Error())
			return
		}
		it := item{Name: in.Name, Stock: in.Stock}
		err := pool.QueryRow(r.Context(), "INSERT INTO items (name, stock) VALUES ($1, $2) RETURNING id",
			it.Name, it.Stock).Scan(&it.ID)
		if err != nil {
			dbError(w, err)
			return
		}
		w.Header().Set("Location", fmt.Sprintf("/api/items/%d", it.ID))
		writeJSON(w, http.StatusCreated, it)
	})

	ln, err := net.Listen("tcp", ":"+port)
	if err != nil {
		return err
	}
	logger.Info("listening", "port", port)
	return http.Serve(ln, logRequests(logger, mux))
}

type statusRecorder struct {
	http.ResponseWriter
	status int
}

func (s *statusRecorder) WriteHeader(code int) {
	s.status = code
	s.ResponseWriter.WriteHeader(code)
}

func logRequests(logger *slog.Logger, next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		start := time.Now()
		requestID := uuid.NewString()
		w.Header().Set("X-Request-Id", requestID)
		rec := &statusRecorder{ResponseWriter: w, status: http.StatusOK}
		next.ServeHTTP(rec, r)
		logger.Info("request",
			"request_id", requestID,
			"method", r.Method,
			"path", r.URL.Path,
			"status", rec.status,
			"duration_ms", time.Since(start).Milliseconds(),
		)
	})
}

func writeJSON(w http.ResponseWriter, status int, body any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	json.NewEncoder(w).Encode(body)
}

func writeError(w http.ResponseWriter, status int, msg string) {
	writeJSON(w, status, map[string]string{"error": msg})
}
